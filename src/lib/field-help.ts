export function fieldHelpText(label: string): string | null {
  const l = label.toLowerCase().replace(/[?*]/g, "").trim();
  for (const [re, text] of HELP) if (re.test(l)) return text;
  if (/^\d+$/.test(l) || l.length < 3) return null;
  return `Informação “${label}” usada nesta etapa e repassada às próximas quando você avança.`;
}
